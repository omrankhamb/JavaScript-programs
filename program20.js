arr = [1,2,3,4,5,6,7,8]

console.log(arr.length) // give the length of arr

// Adding elemet from the last
arr.push(9)
console.log(arr)

// remove the last element from last
arr.pop()
console.log(arr)

// Adding element from first
arr.unshift(10);
console.log(arr)

// Removing element from first
arr.shift();
console.log(arr);